// Regenerate Settings defaults from the two shipped keymaps.
import { readFile, writeFile } from "node:fs/promises";
import { shippedKeymap } from "../kanso/mods/kanso-panel/platform-keymap.js";

const root = new URL("../", import.meta.url);
const files = [...new Set(["macos", "windows"].map(shippedKeymap))];
const maps = Object.fromEntries(await Promise.all(files.map(async (file) => [file, JSON.parse(await readFile(new URL(file, root), "utf8"))])));
await writeFile(new URL("kanso/mods/kanso-settings/defaults.js", root), `// Generated by scripts/sync-keys.mjs.
export const DEFAULT_KEYS = ${JSON.stringify(maps, null, 2)};
`);
